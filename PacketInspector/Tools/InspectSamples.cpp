static void DumpSample(const char* Name, const uint8_t* Data, uint32_t Length)
{
    FomInspectResult Inspect{};
    uint32_t PayloadOffsetBits = 0;
    uint32_t PayloadBitLength = 0;
    const bool Ok = ParseRakInternalPayloadBits(Data, Length, &Inspect, &PayloadOffsetBits, &PayloadBitLength);
    std::printf("%s: ok=%d payloadOffsetBits=%u payloadBitLength=%u\n", Name, Ok ? 1 : 0, PayloadOffsetBits, PayloadBitLength);

    if (!Ok || PayloadBitLength == 0)
    {
        return;
    }

    const uint32_t PayloadBytes = BitsToBytes(PayloadBitLength);
    std::vector<uint8_t> Payload(PayloadBytes);
    RakBitReader Reader(Data, Length);
    Reader.Offset = PayloadOffsetBits;
    if (!Reader.ReadBits(Payload.data(), PayloadBitLength, true))
    {
        std::printf("  read payload failed\n");
        return;
    }

    FomInspectResult PayloadInspect{};
    InspectPayloadIds(Payload.data(), PayloadBytes, &PayloadInspect);
    std::printf("  payload[0]=0x%02X effective=0x%02X layer=%s\n",
                Payload[0],
                PayloadInspect.EffectiveId,
                PayloadInspect.Layer == FomLayerLith ? "Lith" : "Rak");
}

